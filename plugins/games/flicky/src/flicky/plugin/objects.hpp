#pragma once

#include <QSize>
#include <QString>
#include <QStringList>

// What Flicky's level object fields mean to an editor: titles, map footprints,
// which layer they belong to and which type changes keep the data valid.
namespace rl::flicky::objects {

inline constexpr int kRounds = 48;
inline constexpr int kLayouts = 36;
inline constexpr int kMapWidth = 32;
inline constexpr int kMapHeight = 28;
inline constexpr int kLockedRows = 2;   // generated by the game, not stored

// Round indices are 0-based; every fourth round, starting with round 3, is a
// bonus round drawn from the bonus tables instead of a layout.
[[nodiscard]] constexpr bool isBonusRound(int round) {
    return (round + 1) % 4 == 3;
}

// Fields shown on the Objects layer and on the Background layer.
[[nodiscard]] QStringList objectLayerFields();
[[nodiscard]] QStringList backgroundLayerFields();

[[nodiscard]] QString title(const QString& field);

// Cells covered by the visible sprite or tile block, anchored at the stored
// position. Sprites extend below their anchor.
[[nodiscard]] QSize footprint(const QString& field);

// "Single" fields hold exactly one position (player, doors, arrow); spawners
// have a fixed count. Variable fields can grow and shrink.
[[nodiscard]] bool isSingle(const QString& field);
[[nodiscard]] bool isVariable(const QString& field);

// Fields a placement of `field` can be turned into without changing the
// record layout: variable fields of the same special/regular class.
[[nodiscard]] QStringList typeCandidates(const QString& field);

// Encoding note for the inspector's engine data.
[[nodiscard]] QString encoding(const QString& field);

}  // namespace rl::flicky::objects
